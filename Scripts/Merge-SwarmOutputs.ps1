# Merge-SwarmOutputs.ps1 - Updated from Gemini thread
[CmdletBinding()]
param(
 [Parameter(Mandatory = $true)]
 [array]$SwarmResponses # Array of PSCustomObjects containing individual agent outputs
)

Write-Host "[Compiler] Waking up Swarm Results Aggregator..." -ForegroundColor Magenta

$CompiledCodeBlocks = @()
$SystemDirectives = @()
$AuditLog = @()

foreach ($Response in $SwarmResponses) {
 $AgentID = if ($Response.AgentID) { $Response.AgentID } else { "Unknown" }
 $Specialty = if ($Response.Specialty) { $Response.Specialty } else { "General" }
 
 Write-Host "[Compiler] Parsing data package from Agent: $AgentID ($Specialty)" -ForegroundColor DarkGray

 # 1. Categorize and sort inbound text payload pieces
 if ($Response.PayloadType -eq "SourceCode") {
 $CompiledCodeBlocks += "# --- Code block from agent [$AgentID] ---"
 $CompiledCodeBlocks += $Response.Content
 }
 elseif ($Response.PayloadType -eq "SystemDirective") {
 $SystemDirectives += $Response.Content
 }

 $AuditLog += "[Processed] Verified integrity hash for $AgentID payload."
}

# 2. De-duplicate directives and verify code alignment
$UniqueDirectives = $SystemDirectives | Select-Object -Unique

# 3. Assemble the unified master script file payload
$MergedScriptText = @"
# ==============================================================================
# AUTONOMOUSLY SYNTHESIZED MASTER SKILL MODULE
# Generated by: Apex Swarm Framework
# Directives Followed: $($UniqueDirectives -join ', ')
# ==============================================================================
[CmdletBinding()]
param()

try {
 $($CompiledCodeBlocks -join "`n`n")
}
catch {
 Write-Error "[Runtime Exception] Swarm-synthesized element failed: `$(`$_.Exception.Message)"
}
"@

# 4. Return clean, unified custom manifest object
return [PSCustomObject]@{
 SynthesisTimestamp = (Get-Date).ToString("o")
 CompleteScriptText = $MergedScriptText
 AssemblyAuditTrails = $AuditLog
}
