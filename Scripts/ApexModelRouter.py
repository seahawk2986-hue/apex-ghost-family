import os
import json
import urllib.request

class ApexModelRouter:
    def __init__(self):
        # Establish zero-fee local infrastructure routes 
        self.api_url = "http://localhost:11434/v1/chat/completions"
        self.model_name = "qwen2.5-coder:3b"
        print(f"[Model Router] Local routing active. Target: Ollama ({self.model_name})")

    def route_request(self, system_prompt, user_prompt):
        """
        Routes the task payload straight to the active local server port,
        bypassing external network channels to enforce total host safety.
        """
        # Package data into a standard OpenAI-compatible post request payload
        payload = {
            "model": self.model_name,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt}
            ],
            "temperature": 0.2
        }
        
        data = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(self.api_url, data=data, headers={"Content-Type": "application/json"})
        
        try:
            # Execute the direct local server handshake loop
            with urllib.request.urlopen(req, timeout=60) as response:
                res_data = json.loads(response.read().decode("utf-8"))
                # Extract raw code or text variables generated by the local brain
                return res_data["choices"][0]["message"]["content"]
        except Exception as e:
            print(f"[Router Error] Failed to communicate with local server: {str(e)}")
            print("[Router Error] Please ensure Docker or the Ollama background daemon is actively running.")
            return None

# Maintain compatibility hooks for external sub-agent wrappers
def get_model_response(system_instruction, user_instruction):
    router = ApexModelRouter()
    return router.route_request(system_instruction, user_instruction)

