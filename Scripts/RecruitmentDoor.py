def card_digest(card):
    core = {k0: v0 for k0, v0 in card.items() if k0 != "invite"}
    return hashlib.sha256(json.dumps(core, sort_keys=True).encode()).hexdigest()


def invite_issue(capabilities=("mine", "triage"), expires_s=86400):
    sk = keys()
    iid = os.urandom(8).hex()
    inv = {"invite_id": iid, "issued": time.strftime("%Y-%m-%d %H:%M:%S"),
           "expires_at": time.time() + expires_s,
           "capabilities": list(capabilities), "single_use": True}
    sig = sk.sign(json.dumps(inv, sort_keys=True).encode())
    inv["sig_hex"] = sig.signature.hex()
    invs = json.load(open(INVITES, encoding="utf-8-sig")) if os.path.exists(INVITES) else {}
    invs[iid] = inv
    with open(INVITES, "w", encoding="utf-8") as f:
        json.dump(invs, f, indent=1)
    log("invite_issued", invite_id=iid, expires_in_s=expires_s)
    return inv


def invite_valid(inv):
    if not inv or "sig_hex" not in inv:
        return False, "no signature"
    invs = json.load(open(INVITES, encoding="utf-8-sig")) if os.path.exists(INVITES) else {}
    iid = inv.get("invite_id")
    if iid not in invs:
        return False, "unknown invite"
    canonical = json.dumps({k0: v0 for k0, v0 in inv.items() if k0 != "sig_hex"}, sort_keys=True)
    vk = keys().verify_key
    try:
        vk.verify(canonical.encode(), bytes.fromhex(inv["sig_hex"]))
    except Exception:
        return False, "signature verify FAILED (forged or tampered)"
    if time.time() > inv.get("expires_at", 0):
        return False, "invite expired"
    if invs[iid].get("used"):
        return False, "invite already used (single-use, BOINC attach discipline)"
    return True, "valid"


def probe_nonce(agent_name):
    n = os.urandom(16).hex()
    expect = hashlib.sha256((n + agent_name + "apex-probe").encode()).hexdigest()
    with open(os.path.join(AD, "probe_nonce.json"), "w", encoding="utf-8") as f:
        json.dump({"nonce": n, "expected": expect, "issued": time.time()}, f)
    return n, expect


def probe_verify(answer):
    try:
        d = json.load(open(os.path.join(AD, "probe_nonce.json"), encoding="utf-8-sig"))
    except Exception:
        return False, "no probe outstanding"
    if time.time() > d["issued"] + 300:
        return False, "probe expired (300s)"
    return (answer or "").strip() == d["expected"], \
           ("probe VERIFIED" if (answer or "").strip() == d["expected"] else "probe result WRONG")


