def heartbeat(agent_name):
    reg = json.load(open(REGISTRY, encoding="utf-8-sig")) if os.path.exists(REGISTRY) else {"members": {}}
    if agent_name not in reg.get("members", {}):
        return False, "not a member"
    reg["members"][agent_name]["last_seen"] = time.time()
    with open(REGISTRY, "w", encoding="utf-8") as f:
        json.dump(reg, f, indent=1)
    return True, "alive"


def reap():
    reg = json.load(open(REGISTRY, encoding="utf-8-sig")) if os.path.exists(REGISTRY) else {"members": {}}
    gone = [n for n, m0 in reg.get("members", {}).items()
            if time.time() - m0.get("last_seen", 0) > HEARTBEAT_MAX_S]
    for n in gone:
        del reg["members"][n]
        log("EXPELLED", reason="heartbeat lapse (Enclawed lease law)", agent=n)
    if gone:
        with open(REGISTRY, "w", encoding="utf-8") as f:
            json.dump(reg, f, indent=1)
    return gone


